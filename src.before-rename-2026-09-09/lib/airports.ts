export const AIRPORTS: Airport[] = A.map(([iata, name, city, country]) => ({ iata, name, city, country }));

const BY_CODE = new Map(AIRPORTS.map(a => [a.iata, a] as const));

export function airportByCode(code: string): Airport | undefined {
  return BY_CODE.get(code.toUpperCase());
}

/** Format like "JFK — John F. Kennedy Intl, New York". */
export function airportLabel(a: Airport): string {
  return `${a.iata} — ${a.name}, ${a.city}`;
}

/** Case-insensitive substring match against IATA / city / airport name / country. */
export function searchAirports(query: string, limit = 25): Airport[] {
  const q = query.trim().toLowerCase();
  if (!q) return AIRPORTS.slice(0, limit);
  // Prioritize exact-IATA match, then prefix-on-IATA, then any field substring.
  const exact: Airport[] = [];
  const iataPrefix: Airport[] = [];
  const other: Airport[] = [];
  for (const a of AIRPORTS) {
    const iata = a.iata.toLowerCase();
    if (iata === q) { exact.push(a); continue; }
    if (iata.startsWith(q)) { iataPrefix.push(a); continue; }
    if (
      a.city.toLowerCase().includes(q) ||
      a.name.toLowerCase().includes(q) ||
      a.country.toLowerCase().includes(q)
    ) {
      other.push(a);
    }
  }
  return [...exact, ...iataPrefix, ...other].slice(0, limit);
}
