import { queries } from '@/lib/db';
import type { RouteIntelStats } from '@/lib/routeIntel';
import { fmtUSD, fmtRelative } from '@/lib/utils';

/**
 * Personalized Route Intelligence — reads the nightly cron output from
 * `user_route_intel`. Shows the LLM prose summary up top (when present)
 * plus the deterministic per-route stats grid. If no row exists yet, the
 * card renders a "still gathering" hint so the dashboard never breaks.
 */
export function UserRouteIntelCard({ userId }: { userId: number }) {
  const row = queries.getUserRouteIntel(userId);
  if (!row) {
    return (
      <div className="card">
        <div className="eyebrow">Your route intelligence</div>
        <h2 className="!mb-2 mt-1">Pattern coming soon</h2>
        <p className="text-sm text-slate-500">
          The nightly bot will analyze your tracked-route polls and produce a personalized buy/wait pattern here. Allow up to 24 hours after your first few polls.
        </p>
      </div>
    );
  }
  let stats: RouteIntelStats | null = null;
  try { stats = JSON.parse(row.stats_json); } catch { /* corrupt JSON — ignore */ }
  if (!stats || stats.routes.length === 0) {
    return (
      <div className="card">
        <div className="eyebrow">Your route intelligence</div>
        <h2 className="!mb-2 mt-1">Still gathering data</h2>
        <p className="text-sm text-slate-500">
          We need a few more poll cycles before a confident pattern emerges. Last analyzed {fmtRelative(row.generated_at)}.
        </p>
      </div>
    );
  }

  return (
    <div className="card relative overflow-hidden">
      <div className="absolute -top-10 -right-10 w-40 h-40 rounded-full bg-brand/10 blur-3xl pointer-events-none" />
      <div className="card-head">
        <div>
          <div className="eyebrow">Your route intelligence · bot summary</div>
          <h2 className="!mb-0">Your buy/wait pattern</h2>
        </div>
        <div className="flex items-center gap-2 text-[10px] uppercase tracking-wide text-slate-400">
          <span>{row.polls_observed.toLocaleString()} polls analyzed</span>
          <span>·</span>
          <span title={`Generated ${row.generated_at} UTC`}>{fmtRelative(row.generated_at)}</span>
        </div>
      </div>

      {row.prose && (
        <p className="text-sm text-slate-700 dark:text-slate-200 leading-relaxed mb-4 relative">
          {row.prose}
          {row.model && (
            <span className="block mt-1 text-[10px] uppercase tracking-wide text-slate-400 font-normal">
              Generated by {row.model}
            </span>
          )}
        </p>
      )}

      {!row.prose && stats.bullets.length > 0 && (
        <ul className="text-sm text-slate-700 dark:text-slate-200 leading-relaxed space-y-1 mb-4 list-disc pl-5">
          {stats.bullets.map((b, i) => <li key={i}>{b}</li>)}
        </ul>
      )}

      <div className="grid md:grid-cols-2 gap-3 mt-2">
        {stats.routes.slice(0, 4).map(r => (
          <div key={`${r.origin}|${r.destination}`} className="p-3 rounded-lg border border-slate-200/70 dark:border-slate-700 bg-slate-50/50 dark:bg-slate-900/30">
            <div className="flex items-baseline justify-between gap-2">
              <div className="font-mono font-semibold text-slate-800 dark:text-slate-100">
                {r.origin} → {r.destination}
              </div>
              <div className="text-[10px] uppercase tracking-wide text-slate-400">{r.polls} polls</div>
            </div>
            <div className="mt-1 flex items-baseline gap-3 flex-wrap">
              <div>
                <span className="text-[10px] uppercase tracking-wide text-slate-400 block">Cheapest seen</span>
                <span className="font-semibold tabular text-emerald-700 dark:text-emerald-400">{fmtUSD(r.cheapest_per_adult)}</span>
              </div>
              <div>
                <span className="text-[10px] uppercase tracking-wide text-slate-400 block">Median</span>
                <span className="font-semibold tabular text-slate-700 dark:text-slate-200">{fmtUSD(r.median_per_adult)}</span>
              </div>
              {r.current_per_adult != null && r.delta_vs_median_pct != null && (
                <div>
                  <span className="text-[10px] uppercase tracking-wide text-slate-400 block">Now</span>
                  <span className={`font-semibold tabular ${r.delta_vs_median_pct < 0 ? 'text-emerald-700 dark:text-emerald-400' : r.delta_vs_median_pct > 5 ? 'text-amber-600' : 'text-slate-600 dark:text-slate-300'}`}>
                    {fmtUSD(r.current_per_adult)}
                    <span className="ml-1 text-[10px]">{r.delta_vs_median_pct >= 0 ? '+' : ''}{r.delta_vs_median_pct}%</span>
                  </span>
                </div>
              )}
            </div>
            <div className="mt-2 flex flex-wrap gap-1.5 text-[10px]">
              {r.best_dow && <span className="px-1.5 py-0.5 rounded bg-brand/10 text-brand-700 dark:text-brand-300 font-semibold">Best DOW: {r.best_dow}</span>}
              {r.cheapest_month && <span className="px-1.5 py-0.5 rounded bg-emerald-100 dark:bg-emerald-900/40 text-emerald-700 dark:text-emerald-300 font-semibold">Cheapest: {r.cheapest_month}</span>}
              {r.sweet_spot_trip_days && <span className="px-1.5 py-0.5 rounded bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-300 font-semibold">Sweet spot: {r.sweet_spot_trip_days}d</span>}
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}
